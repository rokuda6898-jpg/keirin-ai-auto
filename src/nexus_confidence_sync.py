"""Append confidence metadata to saved feeds without prediction or settlement."""

import argparse
from copy import deepcopy
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import tempfile

from nexus_model.forecast_confidence import (
    annotate_conditional_view, annotate_prediction, _aware_time, _existing,
)


ROOT = Path(__file__).resolve().parents[1]


def _read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def _identity(prediction, race_id):
    return json.dumps(dict(race_id=str(race_id), **{key: prediction.get(key) for key in
        ('model_id', 'captured_at', 'source_sha256', 'tickets')}),
        ensure_ascii=False, sort_keys=True, separators=(',', ':'))


def _write(path, content):
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=path.parent,
                prefix='.' + path.name + '.', suffix='.tmp', delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(content)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def annotate_saved_outputs(outputs_dir=None, *, annotated_at=None):
    """Idempotently add metadata; original forecast/result clocks stay intact.

    The conditional source ledger is read-only. No forecast, odds, allocation,
    outcome or settlement is regenerated by this migration.
    """
    outputs = Path(outputs_dir) if outputs_dir is not None else ROOT / 'outputs'
    stamp = annotated_at or datetime.now(timezone.utc).isoformat()
    summary = dict(changed=False, files=[], nexus_annotations=0, conditional_annotations=0,
                   nexus_grades={}, conditional_grades={})
    plans, nexus = [], []
    paths = [outputs / 'nexus_live.json', *sorted((outputs / 'nexus_forecasts').glob('*.json'))]
    known = {}
    for path in paths:
        if not path.exists():
            continue
        original = _read(path)
        value = deepcopy(original)
        rows = value.get('races') if isinstance(value, dict) else value
        if not isinstance(rows, list):
            raise ValueError(f'{path.name} must contain a race list')
        nexus.append((path, original, value, rows))
        for row in rows:
            prediction = row.get('prediction')
            if isinstance(prediction, dict) and prediction.get('tickets') and _existing(prediction.get('confidence')):
                key = _identity(prediction, row.get('race_id'))
                previous = known.get(key)
                if previous is None or (previous['status'] == 'insufficient' and prediction['confidence']['status'] == 'assessed'):
                    known[key] = deepcopy(prediction['confidence'])
    for path, original, value, rows in nexus:
        changed = 0
        for row in rows:
            prediction = row.get('prediction')
            if not isinstance(prediction, dict) or not prediction.get('tickets'):
                continue
            before = deepcopy(prediction.get('confidence'))
            key = _identity(prediction, row.get('race_id'))
            if not _existing(prediction.get('confidence')) and key in known:
                prediction['confidence'] = deepcopy(known[key])
            confidence = annotate_prediction(prediction, annotated_at=stamp)
            changed += before != confidence
            if confidence:
                known.setdefault(key, deepcopy(confidence))
                if path.name == 'nexus_live.json':
                    grade = confidence['grade'] + ':' + confidence['status']
                    summary['nexus_grades'][grade] = summary['nexus_grades'].get(grade, 0) + 1
        if changed:
            if isinstance(value, dict):
                value['confidence_updated_at'] = stamp
            plans.append((path, value))
            summary['nexus_annotations'] += changed
    conditional_path = outputs / 'conditional_live.json'
    if conditional_path.exists():
        original = _read(conditional_path)
        value = deepcopy(original)
        if not isinstance(value, dict) or not isinstance(value.get('races'), list):
            raise ValueError('conditional_live must contain a races list')
        ledger_path = outputs / 'company/conditional_live_ledger.jsonl'
        by_id = {}
        if ledger_path.exists():
            with ledger_path.open(encoding='utf-8-sig') as handle:
                for line in handle:
                    if line.strip():
                        row = json.loads(line)
                        by_id.setdefault(str(row['race_id']), []).append(row)
        changed = 0
        for race in value['races']:
            view = race.get('shadow')
            if not isinstance(view, dict) or not view.get('tickets'):
                continue
            candidates = by_id.get(str(race.get('id')), [])
            when = _aware_time(view.get('snapshot_at'))
            matching = [row for row in candidates if row.get('top12') == view['tickets']
                        and when is not None and _aware_time(row.get('snapshot_at_jst')) == when]
            row = matching[0] if matching else candidates[0] if candidates else None
            before = deepcopy(view.get('confidence'))
            confidence = annotate_conditional_view(view, row, annotated_at=stamp)
            changed += before != confidence
            if confidence:
                grade = confidence['grade'] + ':' + confidence['status']
                summary['conditional_grades'][grade] = summary['conditional_grades'].get(grade, 0) + 1
        if changed:
            value['confidence_updated_at'] = stamp
            plans.append((conditional_path, value))
            summary['conditional_annotations'] = changed
    # Parse and validate every source/output before any replacement is made.
    encoded = [(path, json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False))
               for path, value in plans]
    for path, content in encoded:
        _write(path, content)
        summary['files'].append(str(path.relative_to(outputs)))
    summary['changed'] = bool(plans)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--outputs-dir', type=Path, default=ROOT / 'outputs')
    parser.add_argument('--annotated-at')
    args = parser.parse_args()
    print(json.dumps(annotate_saved_outputs(args.outputs_dir, annotated_at=args.annotated_at), ensure_ascii=False))


if __name__ == '__main__':
    main()
